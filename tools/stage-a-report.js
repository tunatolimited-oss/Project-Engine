/* Stage A checkpoint: the old engine's answer, then the new engine walked
   from the old assumptions to the corrected ones, one correction at a time.
   node tools/stage-a-report.js > docs/STAGE-A-REPORT.md                  */
var FPE = require('../test/loader.js').loadEngine();
var U = FPE.util;
var LD = require('../legacy/defaults.js'), LE = require('../legacy/engine.js');

function money(x) { return (x < 0 ? '−$' : '$') + Math.round(Math.abs(x)).toLocaleString('en-US'); }
function k(x) { return (x < 0 ? '−$' : '$') + (Math.abs(x) / 1e6 >= 1 ? (Math.abs(x) / 1e6).toFixed(2) + 'M' : Math.round(Math.abs(x) / 1000) + 'K'); }
function when(t) { return t == null ? '—' : U.label(t); }

/* ---- the old engine, on its own defaults and on the "7K plan" ---- */
function legacy(mod) {
  var c = LD.defaultConfig(); if (mod) mod(c);
  var r = LE.runSimulation(c), s = r.summary;
  return { buys: r.acquisitions.length, units: s.finalUnits, cf: s.finalMonthlyCashFlow, nw: s.finalNetWorth };
}
var L0 = legacy();
var L7 = legacy(function (c) { c.setup.startingCapital = 0; c.setup.contributions = [{ fromMonth: '2027-01', monthly: 7000 }]; });

/* ---- the new engine ---- */
function run(cfg) {
  var r = FPE.runSimulation(cfg), s = r.summary;
  return { buys: r.acquisitions.length, units: s.units, inc: s.incomeAtTargetReal, fin: s.finalIncomeReal,
           held: s.heldNWReal, sold: s.soldNWReal, pt: s.partTime, quit: s.quit, types: r.acquisitions.map(function (a) { return a.units; }).join('') };
}
var STEPS = [
  ['Old assumptions, run through the new engine', function (c) {
    c.ops.rentMethod = 'ramp'; c.ops.rampMonths = 18;
    c.lending.dscr.rentBasis = 'greater';
    c.rates.convInv = 0.0695; c.rates.dscr = 0.0635; c.lending.dscr.prepayYears = 5;
    c.market.insurance.nearTermUntil = 2041;
    c.market.priceTracksRents = false;
    c.sourcing.score = 'dayOneCoC';
    c.sourcing.library.availableMonths = 999;
    c.sourcing.model = 'flatCap';
    c.lending.gates.dti = false; c.lending.fha.selfSufficiency = false; c.lending.convInv.otherReserves = false;
  }],
  ['Rents reach market only at turnover (no free ramp)', function (c) { c.ops.rentMethod = 'turnover'; }],
  ['DSCR counts the lesser of lease and market rent', function (c) { c.lending.dscr.rentBasis = 'lesser'; }],
  ['Rates from their own sources (7.60% / 7.35%)', function (c) { var d = FPE.defaultConfig(); c.rates.convInv = d.rates.convInv; c.rates.dscr = d.rates.dscr; }],
  ['Insurance +8% only through 2028, then 4%', function (c) { c.market.insurance.nearTermUntil = 2028; }],
  ['One price index (rents ÷ cap rate)', function (c) { c.market.priceTracksRents = true; }],
  ['Deals ranked on stabilized yield', function (c) { c.sourcing.score = 'stabilizedYield'; }],
  ['Listings expire six months after collection', function (c) { c.sourcing.library.availableMonths = 6; }],
  ['Deal supply from channels, not a flat 3 a year', function (c) { c.sourcing.model = 'channels'; }],
  ['Agency gates: DTI, FHA self-sufficiency, Fannie reserves', function (c) { c.lending.gates.dti = true; c.lending.fha.selfSufficiency = true; c.lending.convInv.otherReserves = true; }]
];

function walk(personal) {
  var cfg = FPE.defaultConfig(); if (personal) personal(cfg);
  var out = [];
  STEPS.forEach(function (s) { s[1](cfg); out.push([s[0], run(U.clone(cfg))]); });
  return out;
}
function table(rows) {
  var lines = ['| Step | Buys | Units | Income at Dec 2036 | Income, last 12 mo | Net worth held | If sold | Part-time | Quit |',
               '|---|---:|---:|---:|---:|---:|---:|---|---|'];
  rows.forEach(function (r, i) {
    var x = r[1];
    lines.push('| ' + (i === 0 ? '' : i + '. ') + r[0] + ' | ' + x.buys + ' | ' + x.units + ' | ' + money(x.inc) + ' | ' + money(x.fin) +
      ' | ' + k(x.held) + ' | ' + k(x.sold) + ' | ' + when(x.pt) + ' | ' + when(x.quit) + ' |');
  });
  return lines.join('\n');
}

var W0 = walk();
var W7 = walk(function (c) { c.plan.startingCash = 0; c.plan.contributions = [{ from: '2027-01', monthly: 7000 }]; });
var base = W0[W0.length - 1][1];

